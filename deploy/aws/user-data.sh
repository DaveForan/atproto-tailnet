#!/bin/bash
# ---------------------------------------------------------------------------
# atproto-tailnet  --  EC2 user-data bootstrap script
#
# Designed for Ubuntu 22.04 LTS. Installs Docker, clones the repo, mounts a
# data volume, and starts the production stack.
#
# This script is referenced by the CloudFormation template but can also be
# run manually on any Ubuntu EC2 instance.
#
# Required environment (set via CloudFormation or manually):
#   DATABASE_URL, SESSION_SECRET, PUBLIC_URL, BASE_DOMAIN
# ---------------------------------------------------------------------------
set -euo pipefail
exec > /var/log/atproto-tailnet-setup.log 2>&1

APP_DIR="/opt/atproto-tailnet"
DATA_DIR="/data"
REPO_URL="${REPO_URL:-https://github.com/your-org/atproto-tailnet.git}"
BRANCH="${BRANCH:-main}"

echo "==> [$(date)] Starting atproto-tailnet bootstrap"

# ---------- System packages -----------------------------------------------
echo "==> Updating packages"
apt-get update -y
DEBIAN_FRONTEND=noninteractive apt-get upgrade -y

# ---------- Docker --------------------------------------------------------
echo "==> Installing Docker"
if ! command -v docker &>/dev/null; then
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
fi

apt-get install -y docker-compose-plugin git awscli

# ---------- Data volume ---------------------------------------------------
echo "==> Mounting data volume"
if [ -b /dev/xvdf ] && ! mountpoint -q "$DATA_DIR"; then
  if ! blkid /dev/xvdf; then
    mkfs.ext4 /dev/xvdf
  fi
  mkdir -p "$DATA_DIR"
  mount /dev/xvdf "$DATA_DIR"
  grep -q '/dev/xvdf' /etc/fstab || \
    echo "/dev/xvdf $DATA_DIR ext4 defaults,nofail 0 2" >> /etc/fstab
fi
mkdir -p "$DATA_DIR/headscale"

# ---------- Application ---------------------------------------------------
echo "==> Cloning repository"
if [ -d "$APP_DIR" ]; then
  cd "$APP_DIR"
  git pull origin "$BRANCH"
else
  git clone --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
  cd "$APP_DIR"
fi

# ---------- Environment ---------------------------------------------------
echo "==> Writing .env (if not present)"
if [ ! -f .env ]; then
  cat > .env <<'EOF'
# Generated by user-data.sh -- edit these values
DATABASE_URL=postgresql://atproto_tailnet:CHANGE_ME@localhost:5432/atproto_tailnet
SESSION_SECRET=CHANGE_ME
PORT=3000
PUBLIC_URL=https://tailnets.yourdomain.com
BASE_DOMAIN=ts.yourdomain.com
HEADSCALE_IMAGE=headscale/headscale:0.29.1
HEADSCALE_PORT_RANGE_START=10001
HEADSCALE_PORT_RANGE_END=10100
HEADSCALE_DATA_DIR=/data/headscale
CADDY_ADMIN_URL=http://caddy:2019
LOG_LEVEL=info
CF_API_TOKEN=
POSTGRES_PASSWORD=CHANGE_ME
EOF
  echo "!!! .env created with placeholder values. Edit before starting. !!!"
fi

# ---------- Start stack ---------------------------------------------------
echo "==> Building and starting services"
docker compose -f docker-compose.production.yml pull
docker compose -f docker-compose.production.yml build
docker compose -f docker-compose.production.yml up -d

# ---------- Firewall ------------------------------------------------------
echo "==> Configuring firewall"
if command -v ufw &>/dev/null; then
  ufw allow 22/tcp
  ufw allow 80/tcp
  ufw allow 443/tcp
  ufw allow 443/udp
  ufw allow 10001:10100/tcp
  ufw --force enable
fi

echo "==> [$(date)] Bootstrap complete"
echo "    Health check: curl http://localhost:3000/health"
echo "    Logs: cd $APP_DIR && docker compose -f docker-compose.production.yml logs -f"
