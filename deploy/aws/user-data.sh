#!/bin/bash
# ---------------------------------------------------------------------------
# atproto-tailnet  --  EC2 user-data bootstrap script
#
# Designed for Ubuntu 22.04 LTS. Installs Docker, clones the repo, mounts a
# data volume, and starts the production stack.
#
# This script is referenced by the CloudFormation template but can also be
# run manually on any Ubuntu EC2 instance.
#
# Required environment (set via CloudFormation or manually):
#   DATABASE_URL, SESSION_SECRET, PUBLIC_URL, BASE_DOMAIN, AWS_REGION
# ---------------------------------------------------------------------------
set -euo pipefail
if [ ! -t 0 ]; then
  exec > /var/log/atproto-tailnet-setup.log 2>&1
fi

APP_DIR="/opt/atproto-tailnet"
DATA_DIR="/data"
REPO_URL="${REPO_URL:-https://github.com/your-org/atproto-tailnet.git}"
BRANCH="${BRANCH:-main}"

echo "==> [$(date)] Starting atproto-tailnet bootstrap"

# ---------- System packages -----------------------------------------------
echo "==> Updating packages"
apt-get update -y
DEBIAN_FRONTEND=noninteractive apt-get upgrade -y

# ---------- Docker --------------------------------------------------------
echo "==> Installing Docker"
if ! command -v docker &>/dev/null; then
  # Docker's signed apt repository (not the get.docker.com script). The key
  # fingerprint is checked before apt trusts the repository.
  apt-get install -y ca-certificates curl gnupg
  DOCKER_OS="$(. /etc/os-release && echo "$ID")"
  DOCKER_CODENAME="$(. /etc/os-release && echo "$VERSION_CODENAME")"
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL "https://download.docker.com/linux/${DOCKER_OS}/gpg" -o /etc/apt/keyrings/docker.asc
  DOCKER_KEY_FPR="$(gpg --show-keys --with-colons /etc/apt/keyrings/docker.asc | awk -F: '$1 == "fpr" { print $10; exit }')"
  if [ "$DOCKER_KEY_FPR" != "9DC858229FC7DD38854AE2D88D81803C0EBFCD88" ]; then
    echo "ERROR: unexpected Docker apt key fingerprint: $DOCKER_KEY_FPR" >&2
    rm -f /etc/apt/keyrings/docker.asc
    exit 1
  fi
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/${DOCKER_OS} ${DOCKER_CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -y
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker
fi

apt-get install -y docker-compose-plugin git awscli

# ---------- Data volume ---------------------------------------------------
echo "==> Mounting data volume"
if [ -b /dev/xvdf ] && ! mountpoint -q "$DATA_DIR"; then
  if ! blkid /dev/xvdf; then
    mkfs.ext4 /dev/xvdf
  fi
  mkdir -p "$DATA_DIR"
  mount /dev/xvdf "$DATA_DIR"
  grep -q '/dev/xvdf' /etc/fstab || \
    echo "/dev/xvdf $DATA_DIR ext4 defaults,nofail 0 2" >> /etc/fstab
fi

# ---------- Application ---------------------------------------------------
echo "==> Cloning repository"
if [ -d "$APP_DIR" ]; then
  cd "$APP_DIR"
  git pull origin "$BRANCH"
else
  git clone --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
  cd "$APP_DIR"
fi

# ---------- Environment ---------------------------------------------------
echo "==> Writing .env (if not present)"
if [ ! -f .env ]; then
  cat > .env <<'EOF'
# Generated by user-data.sh -- edit these values

# ── Database (containerized Postgres via docker-compose.coordinator.yml) ──
POSTGRES_USER=atproto_tailnet
POSTGRES_PASSWORD=CHANGE_ME
POSTGRES_DB=atproto_tailnet
DATABASE_URL=postgresql://atproto_tailnet:CHANGE_ME@postgres:5432/atproto_tailnet

# ── App ──
SESSION_SECRET=CHANGE_ME
PORT=3000
PUBLIC_URL=https://tailnets.yourdomain.com
BASE_DOMAIN=ts.yourdomain.com
APP_DOMAIN=tailnets.yourdomain.com
LOG_LEVEL=info

# ── Coordinator ──
COORDINATOR_URL=http://coordinator:9443
COORDINATOR_API_KEY=CHANGE_ME

# ── TLS strategy: Route53 DNS-01 wildcard ──
TLS_STRATEGY=route53
CADDY_DNS_PLUGINS=github.com/caddy-dns/route53
AWS_REGION=us-east-1

# AWS credentials for Route53 DNS-01 (omit if using EC2 instance role)
AWS_ACCESS_KEY_ID=
AWS_SECRET_ACCESS_KEY=

# ── Federation (optional) ──
# FEDERATION_KEY_ENCRYPTION_KEY=
EOF
  echo "!!! .env created with placeholder values. Edit before starting. !!!"
  echo "After editing .env, re-run this script or run:"
  echo "  cd $APP_DIR && docker compose -f docker-compose.coordinator.yml up -d"
  exit 0
fi

# ---------- Start stack ---------------------------------------------------
echo "==> Building and starting services (coordinator mode)"
docker compose -f docker-compose.coordinator.yml build
docker compose -f docker-compose.coordinator.yml up -d

# ---------- Firewall ------------------------------------------------------
echo "==> Configuring firewall"
if command -v ufw &>/dev/null; then
  ufw allow 22/tcp
  ufw allow 80/tcp
  ufw allow 443/tcp
  ufw allow 443/udp
  ufw --force enable
fi

echo "==> [$(date)] Bootstrap complete"
echo "    Health check: curl http://localhost:3000/health"
echo "    Logs: cd $APP_DIR && docker compose -f docker-compose.coordinator.yml logs -f"
